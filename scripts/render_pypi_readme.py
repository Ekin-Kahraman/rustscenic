"""Generate the package README after README/version edits; --check detects drift.

Only link destinations change. GitHub retains its existing README and layout.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/Ekin-Kahraman/rustscenic"
RAW = "https://raw.githubusercontent.com/Ekin-Kahraman/rustscenic"


def render(root: Path = ROOT) -> str:
    version = re.search(r'^version = "([^"]+)"$',
                        (root / "pyproject.toml").read_text(), re.M).group(1)
    ref = f"v{version}"

    def resolve(url: str, image: bool = False) -> str:
        if urlsplit(url).scheme or url.startswith("//"):
            for prefix in (f"{REPO}/blob/", f"{REPO}/tree/", f"{RAW}/",
                           "https://colab.research.google.com/github/Ekin-Kahraman/rustscenic/blob/"):
                if url.startswith(prefix + "main/"):
                    return prefix + ref + "/" + url[len(prefix + "main/"):]
            return url
        if url.startswith("#"):
            return f"{REPO}/blob/{ref}/README.md{url}"
        return f"{RAW}/{ref}/{url}" if image else f"{REPO}/blob/{ref}/{url}"

    def attribute(match: re.Match) -> str:
        name, quote, value = match.groups()
        # Current picture sources each have one URL, without width descriptors.
        return f"{name}={quote}{resolve(value, name != 'href')}{quote}"

    def markdown_image(match: re.Match) -> str:
        prefix, url = match.groups()
        return f"{prefix}({resolve(url, image=True)})"

    source = (root / "README.md").read_text()
    # Do not rewrite example code inside fenced blocks.
    chunks = re.split(r"(```.*?```)", source, flags=re.S)
    for i in range(0, len(chunks), 2):
        chunks[i] = re.sub(r'\b(href|src|srcset)=([\"\'])(.*?)\2', attribute, chunks[i])
        chunks[i] = re.sub(r'(!\[[^\[\]\n]*\])\(([^\s)]+)\)', markdown_image, chunks[i])
        # Resolve images first, then links including an image's enclosing link.
        chunks[i] = re.sub(r'(?<=\]\()([^\s)]+)(?=\))',
                           lambda match: resolve(match.group(0)), chunks[i])
    return "<!-- Generated by scripts/render_pypi_readme.py; edit README.md. -->\n" + "".join(chunks)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "README.pypi.md"
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit("Package README is stale; run python scripts/render_pypi_readme.py")
        print("Package README matches README.md and the package version")
    else:
        target.write_text(expected)
        print(target)
